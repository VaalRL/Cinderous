// 實驗性 FS 的複查期限（ADR-0306 §5）。
//
// 背景：ADR-0306 開了一條**繞過** ADR-0245 上線閘門的路（FS 以實驗性選項出貨）。
// 繞過閘門的臨時方案最容易變成永久，而 2026-07-31 的決定是
// **暫不投任何審計申請**、且**不在產品文案放日期**（使用者決定）
// ⇒ 產品面的自我執行機制沒有了，**這條測試是唯一會提醒我們回來看的東西**。
//
// 它到期時會弄紅 CI，包含不相關的工作。**那是刻意的**——溫和的提醒沒有效果。
import { describe, expect, it } from "vitest";

/** 2027-01-30（UTC）。使用者於 2026-07-31 選定，約六個月。 */
const FS_EXPERIMENTAL_REVIEW_BY = Date.UTC(2027, 0, 30);

describe("實驗性 FS 的複查期限（ADR-0306 §5）", () => {
  it("🔴 期限未到；到期後請**重新決定**，不要只是把日期往後推", () => {
    // ⚠ 看到這條紅了的人：正確的處理**不是**改上面那個日期。先回答這三題——
    //
    //   1. 要投 OTF Security Lab／OpenSats 嗎？（ADR-0290 §2B：OTF 那條**免費**，
    //      成本只有一份申請書；OpenSats 已資助過 NIP-44 函式庫審計，是直接前例。）
    //   2. 若仍不投，理由是什麼？那個理由自 2026-07-31 以來變了嗎？
    //   3. 若要繼續維持實驗性，下次什麼時候再問？
    //
    // 把答案寫進 ADR-0306 §5，再調整這個日期。**沒有答案就不要調。**
    expect(Date.now()).toBeLessThan(FS_EXPERIMENTAL_REVIEW_BY);
  });
});
