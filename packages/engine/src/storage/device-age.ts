// 觀測老化（ADR-0324）：多久沒見到就推定這台已經不在了。
//
// ## 為什麼這不是「清單好看一點」的問題
//
// 裝置觀測清單**只增不減**。ADR-0322 S2a 已經抓過一次這個形狀的錯（布林判定被丟掉的舊手機
// 永遠卡住），並改用證據取代推論。但**證據本身也沒有到期日**——於是同一個病從另一扇門回來：
//
//   - `revocationState()`：某台四個月前的快照帶著 EK ⇒ **永遠報 dual-track**。
//   - `shouldOmitFsKeys()`：某台四個月前觀測到、不在目錄內 ⇒ **這台永遠把 EK 放進自己的快照**
//     ⇒ **撤銷從來沒有真正生效過**。
//
// 第二個才是重點：那不是顯示問題，是**安全性質根本沒開啟**，而且完全靜默。
//
// ## 買不到什麼
//
// 「沒看到」不等於「不存在」。推定已離線的裝置若哪天回來，它拿不到新的 EK
// （因為我們已經停止在快照裡放 EK）⇒ **它會讀不到新訊息**。
// 這是刻意的取捨，成立的前提是**復原路徑看得見**：它一回來就會出現在裝置清單裡、
// 標著「不在目錄內」，按一次授權即可。相對地，不老化的代價是撤銷對**所有人**都不生效，
// 而且沒有任何人看得出來。

/**
 * 推定離線的門檻：**90 天**。
 *
 * 與 `OR_SET_TOMBSTONE_RETENTION_MS` 同一個視野——這個專案已經用 90 天當作
 * 「久到可以放心當作不會再回來」的長度，不另立新標準。
 * 抽屜裡放一個夏天的手機仍在窗內。
 */
export const DEVICE_STALE_MS = 90 * 24 * 60 * 60 * 1000;

/**
 * 這台是否已久未出現。
 *
 * ⚠ `local`（就是這一台）每次啟動都會刷新 `lastSeen`，故不會被判為老化——
 * 真要發生也只可能是時鐘倒退，見下。
 * ⚠ 時鐘倒退（`now < lastSeen`）時回 false：**寧可多等，不要因為時鐘怪怪的就把自己的裝置踢出判斷**。
 */
export function isDeviceStale(d: { lastSeen: number }, now: number = Date.now()): boolean {
  return now - d.lastSeen > DEVICE_STALE_MS;
}
